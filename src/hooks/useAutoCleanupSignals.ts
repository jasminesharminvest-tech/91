import { useEffect } from 'react';
import { useAnalyticsStore, AUTO_CLEANUP_INTERVAL_MS } from '@/stores/useAnalyticsStore';
import { clearOutcomeScheduler } from '@/stores/useTickStore';
import { deleteAllSignals } from '@/lib/signal-persistence';

// Реальные проблемы, п.6: требование "самоудаление раз в сутки" было явно
// озвучено в исходном задании, но в коде было ПРЯМО ПРОТИВОПОЛОЖНОЕ —
// useAnalyticsStore закомментированно требовал очистки "только вручную",
// SignalFeed.tsx дёргал deleteAllSignals() только по клику кнопки, а
// supabase/functions/delete-all-signals/index.ts — это rate-limited полный
// снос ВСЕЙ таблицы по требованию клиента, без расписания и без выборки по
// возрасту записей.
//
// Архитектура — выбор между двумя вариантами (см. также комментарий в
// исходном аудите "Реальные проблемы"):
//
//   А) Клиентская проверка (реализовано здесь): при каждом старте
//      приложения (и раз в час, пока вкладка открыта) сравниваем
//      Date.now() с сохранённой в localStorage/Supabase меткой последнего
//      автоудаления (useAnalyticsStore.lastAutoCleanupAt, персистится
//      через zustand persist) — если прошло >= 24 часов, чистим локальную
//      историю и таблицу trading_signals целиком (тем же путём, что кнопка
//      "Удалить все" — переиспользуем deleteAllSignals()/
//      clearOutcomeScheduler()).
//
//   Б) Серверный pg_cron / Supabase Scheduled Function: DELETE FROM
//      trading_signals WHERE created_at < now() - interval '24 hours' по
//      расписанию, независимо от того, открыто ли приложение у кого-либо
//      в этот момент.
//
// Выбран вариант А, по трём причинам, специфичным именно для этого
// проекта:
//   1) Это client-only SPA (Vite + React), деплоящееся на bolt.new —
//      здесь нет серверной части проекта, которой можно было бы владеть
//      кроме уже существующих Supabase Edge Functions; заводить pg_cron
//      означает отдельную миграцию + `supabase functions deploy` вне
//      этого репозитория, которую нельзя ни протестировать, ни откатить
//      отсюда.
//   2) История задумана как ГЛОБАЛЬНАЯ (см. комментарий в
//      useAnalyticsStore.ts) и уже имеет единственный canonical путь
//      полной очистки — edge-функция delete-all-signals с rate-limit и
//      service-role ключом (см. её аудит по безопасности). Вариант А
//      просто вызывает этот же самый путь автоматически, не создавая
//      второй, отдельно поддерживаемый механизм удаления с другими
//      правами доступа.
//   3) localStorage — это единственное хранилище истории, когда Supabase
//      не сконфигурирован (см. signal-persistence.ts, "fallback в
//      localStorage") — pg_cron физически не может его почистить, т.к. не
//      имеет доступа к браузеру пользователя. Клиентская проверка работает
//      одинаково в обоих режимах (с БД и без неё).
//
// Компромисс варианта А: если приложение не открывалось дольше суток,
// очистка выполнится с опозданием — в момент следующего открытия, а не
// ровно по расписанию. Для нужд этой фичи ("не копить и не захламлять
// систему") это приемлемо: цель — не бесконечный рост, а не точность
// до минуты. Если в будущем понадобится гарантия "чистится даже когда
// никто не открывал приложение" — тогда стоит добавить вариант Б поверх
// (они не взаимоисключающие: серверный pg_cron может быть дополнительной
// подстраховкой, а не заменой).
export function useAutoCleanupSignals(): void {
  useEffect(() => {
    const check = () => {
      const ran = useAnalyticsStore.getState().maybeRunAutoCleanup();
      if (!ran) return;
      // Тот же побочный эффект, что и ручная очистка в SignalFeed.tsx:
      // гасим очередь OutcomeScheduler (module-level синглтон, независимый
      // от этого стора), иначе уже запланированные сигналы продолжали бы
      // резолвиться в фоне и обучать калибровочную модель трейдами,
      // которых с точки зрения истории больше не существует, и синхронно
      // просим сервер снести таблицу trading_signals (no-op, если
      // Supabase не сконфигурирован — см. deleteAllSignals()).
      clearOutcomeScheduler();
      void deleteAllSignals();
    };

    // Сразу при монтировании (покрывает и "первый запуск после установки
    // фичи" — см. maybeRunAutoCleanup, и "прошли сутки с последнего визита").
    check();

    // Плюс периодически, пока вкладка открыта — чтобы сессия, которая
    // держится непрерывно открытой дольше суток (см. useWakeLock.ts),
    // тоже дождалась автоочистки, а не только следующая перезагрузка.
    const interval = setInterval(check, Math.min(AUTO_CLEANUP_INTERVAL_MS, 60 * 60 * 1000));
    return () => clearInterval(interval);
  }, []);
}
